#!/usr/bin/env python3
"""BenchPod error codes: generate the firmware header, the hosts' JSON and the docs table from
errors/catalog.toml (the one source of truth; its header explains the rules).

  python3 tools/gen_errors.py           write the outputs
  python3 tools/gen_errors.py --check   fail when a committed output is stale (CI), or when a code
                                        a released tag already has still says since = "next"
  python3 tools/gen_errors.py --release 3.10.14
                                        the release pull request: every since = "next" becomes the
                                        version, then the outputs are written
  python3 tools/gen_errors.py --check-release 3.10.14
                                        the release workflow: nothing "next" is left

Outputs (never hand-edit them: the banner says so):
  stm32h563/src/bp_errors.h   the code enum and one typed bp_err_<name>() per code
  errors/errors.json          everything the hosts need (SDK, CLI, MCP, server, web, docs pages)
  errors/ERRORS.md            a human-readable table
"""
import hashlib
import json
import os
import re
import subprocess
import sys
import tomllib

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(REPO, "errors", "catalog.toml")
OUT_H = os.path.join(REPO, "stm32h563", "src", "bp_errors.h")
OUT_JSON = os.path.join(REPO, "errors", "errors.json")
OUT_MD = os.path.join(REPO, "errors", "ERRORS.md")

SURFACES = ("sdk", "cli", "mcp", "web")
ARG_TYPES = ("int", "str")
CODE_RE = re.compile(r"^BP\d{4}$")
NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")
ARG_RE = re.compile(r"^[a-z][a-z0-9_]*$")
FIELD_RE = re.compile(r"\{([a-z0-9_]+)\}")
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+$")
BANNER = "GENERATED by tools/gen_errors.py from errors/catalog.toml. DO NOT EDIT: edit the catalog."


def load():
    with open(CATALOG, "rb") as f:
        raw = f.read()
    return tomllib.loads(raw.decode("utf-8")), hashlib.sha256(raw).hexdigest()


def validate(cat):
    errors = []
    names = set()
    expected = 1
    for code in cat:
        e = cat[code]
        where = code
        if not CODE_RE.match(code):
            errors.append(f"{where}: codes look like BP0001")
            continue
        if int(code[2:]) != expected:
            errors.append(f"{where}: codes must be in order without gaps (expected BP{expected:04d}); "
                          "never renumber: add new codes at the end")
        expected = int(code[2:]) + 1
        for key in ("name", "area", "since", "message", "cause", "fix"):
            if key not in e:
                errors.append(f"{where}: missing {key}")
        unknown = set(e) - {"name", "area", "since", "message", "cause", "fix", "args", "retired",
                            "replaced_by", "docs"}
        if unknown:
            errors.append(f"{where}: unknown keys {sorted(unknown)}")
        name = e.get("name", "")
        if not NAME_RE.match(name):
            errors.append(f"{where}: name must be snake_case")
        if name in names:
            errors.append(f"{where}: name {name} is used twice")
        names.add(name)
        args = e.get("args", {})
        for a, t in args.items():
            if not ARG_RE.match(a):
                errors.append(f"{where}: arg {a} must be snake_case")
            if t not in ARG_TYPES:
                errors.append(f"{where}: arg {a} has type {t!r}, expected one of {ARG_TYPES}")
        fix = e.get("fix", {})
        for s in SURFACES:
            if not fix.get(s):
                errors.append(f"{where}: fix.{s} is missing")
        if set(fix) - set(SURFACES):
            errors.append(f"{where}: unknown fix surfaces {sorted(set(fix) - set(SURFACES))}")
        texts = {"message": e.get("message", ""), "cause": e.get("cause", "")}
        texts.update({f"fix.{s}": fix.get(s, "") for s in SURFACES})
        if isinstance(e.get("docs"), str):
            texts["docs"] = e["docs"]
        for field, text in texts.items():
            for ref in FIELD_RE.findall(text):
                if ref not in args:
                    errors.append(f"{where}: {field} uses {{{ref}}} but there is no such arg")
            if "—" in text or "–" in text:
                errors.append(f"{where}: {field} has an em or en dash (house style: none)")
        since = e.get("since", "next")
        if since != "next" and not VERSION_RE.match(str(since)):
            errors.append(f"{where}: since must be a version (3.10.11) or \"next\"")
        if "replaced_by" in e and e["replaced_by"] not in cat:
            errors.append(f"{where}: replaced_by {e['replaced_by']} is not a code")
    return errors


def c_ident(name):
    return "BP_E_" + name.upper()


def gen_h(cat):
    out = [f"/* {BANNER} */", "#ifndef BP_ERRORS_H", "#define BP_ERRORS_H", "",
           "/* Stable error codes (errors/catalog.toml). A handler refuses with bp_err_<name>(conn_id,",
           "   BP_ERR_TEXT(\"...\"), args...): the reply carries the code and the args, and the text when",
           "   the build keeps it. Built with -DBP_ERRORS_NO_TEXT, BP_ERR_TEXT() is NULL, the strings",
           "   drop out of the binary, and the reply's message is the compact fallback",
           "   (\"BP0002 cmd=foo\") that bp_error_format builds from the code and args. The hosts",
           "   render the message, the fix and the docs link from errors/errors.json. */", "",
           "#include <stddef.h>", "#include <stdint.h>", "",
           "#ifdef BP_ERRORS_NO_TEXT", "#define BP_ERR_TEXT(s) ((const char *)0)", "#else",
           "#define BP_ERR_TEXT(s) (s)", "#endif", "",
           "typedef enum {", "    BP_E_NONE = 0,"]
    for code, e in cat.items():
        tag = "   /* retired */" if "retired" in e else ""
        out.append(f"    {c_ident(e['name'])} = {int(code[2:])},{tag}")
    out += ["} bp_errcode_t;", "",
            "/* One value sent with a code: key, and either a string (is_str) or an integer. */",
            "typedef struct { const char *key; const char *s; int32_t i; uint8_t is_str; } bp_err_arg_t;",
            "",
            "/* The reply line ({\"status\":\"error\",\"code\":\"BP0002\",\"args\":{...},\"message\":...}\\n)",
            "   into buf; returns its length, 0 when it does not fit (bp_errors.c). */",
            "size_t bp_error_format(char *buf, size_t cap, bp_errcode_t code, const char *text,",
            "                       const bp_err_arg_t *args, size_t n);",
            "/* Formats and sends it on a connection (command_handler.c). */",
            "void bp_error_send(int conn_id, bp_errcode_t code, const char *text,",
            "                   const bp_err_arg_t *args, size_t n);", ""]
    for code, e in cat.items():
        if "retired" in e:
            continue
        args = e.get("args", {})
        params = "".join(f", {'const char *' if t == 'str' else 'int32_t '}{a}" for a, t in args.items())
        out.append(f"/* {code}: {e['message']} */")
        out.append(f"static inline void bp_err_{e['name']}(int conn_id, const char *text{params}) {{")
        if args:
            items = ", ".join(
                f'{{"{a}", {a}, 0, 1}}' if t == "str" else f'{{"{a}", 0, {a}, 0}}' for a, t in args.items())
            out.append(f"    const bp_err_arg_t a[] = {{ {items} }};")
            out.append(f"    bp_error_send(conn_id, {c_ident(e['name'])}, text, a, {len(args)});")
        else:
            out.append(f"    bp_error_send(conn_id, {c_ident(e['name'])}, text, 0, 0);")
        out.append("}")
    out += ["", "#endif /* BP_ERRORS_H */", ""]
    return "\n".join(out)


def gen_json(cat, digest):
    codes = {}
    for code, e in cat.items():
        entry = {k: e[k] for k in ("name", "area", "since", "message", "cause") if k in e}
        entry["args"] = e.get("args", {})
        entry["fix"] = {s: e["fix"][s] for s in SURFACES}
        for k in ("retired", "replaced_by", "docs"):
            if k in e:
                entry[k] = e[k]
        codes[code] = entry
    doc = {"_generated": BANNER, "version": 1, "catalog_sha256": digest,
           "docs_url": "https://embeddedci.com/docs/errors#{code}", "codes": codes}
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def gen_md(cat):
    out = [f"<!-- {BANNER} -->", "", "# BenchPod error codes", "",
           "The public page is https://embeddedci.com/docs/errors (one anchor per code). Rules for adding a code: "
           "the header of `errors/catalog.toml`.", "",
           "| Code | Name | Area | Since | Message |", "|---|---|---|---|---|"]
    for code, e in cat.items():
        since = e["since"] + (f", retired {e['retired']}" if "retired" in e else "")
        out.append(f"| {code} | `{e['name']}` | {e['area']} | {since} | {e['message']} |")
    return "\n".join(out) + "\n"


def release(version):
    """The release pull request: since = "next" -> since = "<version>" in the catalog."""
    if not VERSION_RE.match(version):
        raise SystemExit(f"gen_errors: {version!r} is not a version")
    with open(CATALOG, encoding="utf-8") as f:
        text = f.read()
    text, n = re.subn(r'^since = "next"$', f'since = "{version}"', text, flags=re.M)
    with open(CATALOG, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"gen_errors: release {version}: {n} code(s) stamped")


def released_codes():
    """The codes of the newest release tag (vX.Y.Z) that has the catalog; empty without git or
    tags (a shallow CI checkout), so the check is skipped there rather than failing."""
    try:
        tags = subprocess.run(["git", "-C", REPO, "tag", "-l", "v[0-9]*", "--sort=-version:refname"],
                              capture_output=True, text=True, check=True).stdout.split()
    except (OSError, subprocess.CalledProcessError):
        return "", set()
    for tag in tags:
        if not VERSION_RE.match(tag[1:]):
            continue
        r = subprocess.run(["git", "-C", REPO, "show", f"{tag}:errors/catalog.toml"],
                           capture_output=True, text=True)
        if r.returncode == 0:
            return tag, set(tomllib.loads(r.stdout))
    return "", set()


def main():
    argv = sys.argv[1:]
    if len(argv) == 2 and argv[0] == "--release":
        release(argv[1])
        argv = []
    check = bool(argv) and argv[0] in ("--check", "--check-release")
    cat, digest = load()
    problems = validate(cat)
    if check:
        tag, shipped = released_codes()
        for code in sorted(shipped & set(cat)):
            if cat[code].get("since") == "next":
                problems.append(f"{code}: since is \"next\" but {tag} already has it: stamp the "
                                "release it first shipped in")
    if len(argv) == 2 and argv[0] == "--check-release":
        nxt = [code for code, e in cat.items() if e.get("since") == "next"]
        if nxt:
            problems.append(f"release {argv[1].lstrip('v')}: still \"next\": {', '.join(nxt)} "
                            f"(run tools/gen_errors.py --release {argv[1].lstrip('v')})")
    if problems:
        print("errors/catalog.toml:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    outputs = {OUT_H: gen_h(cat), OUT_JSON: gen_json(cat, digest), OUT_MD: gen_md(cat)}
    stale = []
    for path, text in outputs.items():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old == text:
            continue
        if check:
            stale.append(os.path.relpath(path, REPO))
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print("wrote", os.path.relpath(path, REPO))
    if stale:
        print("stale (run python3 tools/gen_errors.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
