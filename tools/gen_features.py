#!/usr/bin/env python3
"""BenchPod features: generate the hosts' JSON and the firmware header from features/features.toml
(the one source of truth; its header explains the rules), and check the table against the code.

  python3 tools/gen_features.py                       write the outputs
  python3 tools/gen_features.py --check               fail when an output is stale or a check fails (CI)
  python3 tools/gen_features.py --release 3.10.11     the release pull request: "next" becomes the
                                                      version and a [[releases]] row is added
  python3 tools/gen_features.py --check-release 3.10.11
                                                      the release workflow: nothing "next", a row for it

Outputs (never hand-edit them: the banner says so):
  features/features.json        everything the hosts need (SDK, MCP, CLI, server, web)
  stm32h563/src/bp_features.h   BP_FEATURES_REV, the revision the pod announces as features_rev,
                                and BP_API / BP_MIN_CLIENT_API, the client API level and the
                                lowest client_api the pod takes

Checks (also with --check):
  - api is an integer >= 1, min_client_api an integer >= 0, and min_client_api <= api
  - each entry's gateware equals the firmware constant its gw_const names (stm32h563/src/*.h)
  - the status caps list is frozen: every name cloud_caps_emit_list writes is an entry's or a
    fact's legacy_caps, and only revision-1 entries (the list as it was) have one
  - every `docs` link that is not a full URL names a file under docs/ that exists, and its
    #anchor is a heading there (GitHub's slug rules) or an <a id="..."> in it
"""
import datetime
import hashlib
import json
import os
import re
import sys
import tomllib

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(REPO, "features", "features.toml")
OUT_JSON = os.path.join(REPO, "features", "features.json")
OUT_H = os.path.join(REPO, "stm32h563", "src", "bp_features.h")
SRC = os.path.join(REPO, "stm32h563", "src")
CAPS_C = os.path.join(SRC, "cloud_caps.c")
MANIFEST = os.path.join(REPO, "ice40", "release", "MANIFEST")
BANNER = "GENERATED by tools/gen_features.py from features/features.toml. DO NOT EDIT: edit the table."

NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+$")
BOARDS = ("any", "analog", "digital")
IMAGES = ("loop", "deep", "emu")
FEATURE_KEYS = {"rev", "firmware", "gateware", "gw_const", "board", "requires", "legacy_caps",
                "legacy_frame", "docs", "status", "dated", "note"}
FACT_KEYS = {"status", "frame", "hw", "legacy_caps", "note"}
DATED = ("tag", "floor", "code")


def vtuple(v):
    return tuple(int(x) for x in v.split("."))


def load():
    with open(TABLE, "rb") as f:
        raw = f.read()
    return tomllib.loads(raw.decode("utf-8")), hashlib.sha256(raw).hexdigest()


def fw_constants():
    """NAME -> value of every `#define NAME <n>u` in the firmware headers."""
    consts = {}
    pat = re.compile(r"^\s*#define\s+([A-Z0-9_]+)\s+(\d+)u?\b", re.M)
    for name in sorted(os.listdir(SRC)):
        if name.endswith(".h"):
            with open(os.path.join(SRC, name), encoding="utf-8") as f:
                for m in pat.finditer(f.read()):
                    consts.setdefault(m.group(1), int(m.group(2)))
    return consts


def status_caps_names():
    """The names cloud_caps_emit_list can write into the status caps list."""
    with open(CAPS_C, encoding="utf-8") as f:
        src = f.read()
    start = src.find("void cloud_caps_emit_list")
    if start < 0:
        raise SystemExit("gen_features: no cloud_caps_emit_list in cloud_caps.c")
    end = src.find("\n}\n", start)
    body = re.sub(r"/\*.*?\*/", "", src[start:end], flags=re.S)
    return set(re.findall(r'\\"([a-z0-9_]+)\\"', body)) - {"caps"}


def validate(t):
    errs = []
    for key in ("schema", "revision", "api", "min_client_api", "floor", "docs_base", "facts",
                "features", "releases"):
        if key not in t:
            errs.append(f"missing top-level {key}")
    if errs:
        return errs
    if t["schema"] != 1:
        errs.append("schema must be 1")
    api, min_api = t["api"], t["min_client_api"]
    if not isinstance(api, int) or isinstance(api, bool) or api < 1:
        errs.append("api must be an integer >= 1")
    elif not isinstance(min_api, int) or isinstance(min_api, bool) or min_api < 0:
        errs.append("min_client_api must be an integer >= 0")
    elif min_api > api:
        errs.append(f"min_client_api {min_api} is above api {api}: the pod would refuse every "
                    "client, the newest included")
    if not VERSION_RE.match(t["floor"]):
        errs.append("floor is not a version")
    facts = t["facts"]
    for name, f in facts.items():
        if not NAME_RE.match(name):
            errs.append(f"fact {name}: bad name")
        if set(f) - FACT_KEYS:
            errs.append(f"fact {name}: unknown keys {sorted(set(f) - FACT_KEYS)}")
        if not ({"status", "frame", "hw"} & set(f)):
            errs.append(f"fact {name}: needs status, frame or hw")
    revs = []
    for name, e in t["features"].items():
        where = f"feature {name}"
        if not NAME_RE.match(name):
            errs.append(f"{where}: bad name")
        if set(e) - FEATURE_KEYS:
            errs.append(f"{where}: unknown keys {sorted(set(e) - FEATURE_KEYS)}")
        for key in ("rev", "firmware", "dated"):
            if key not in e:
                errs.append(f"{where}: missing {key}")
        if not isinstance(e.get("rev"), int) or e.get("rev", 0) < 1:
            errs.append(f"{where}: rev must be an integer >= 1")
        else:
            revs.append(e["rev"])
            if e["rev"] > t["revision"]:
                errs.append(f"{where}: rev {e['rev']} is above revision {t['revision']}")
        fw = e.get("firmware", "")
        if fw != "next" and not VERSION_RE.match(str(fw)):
            errs.append(f"{where}: firmware must be a version or \"next\"")
        elif fw != "next" and vtuple(fw) < vtuple(t["floor"]):
            errs.append(f"{where}: firmware {fw} is below the floor {t['floor']}: say the floor")
        if ("gateware" in e) != ("gw_const" in e):
            errs.append(f"{where}: gateware and gw_const go together")
        if e.get("board", "any") not in BOARDS:
            errs.append(f"{where}: board must be one of {BOARDS}")
        for r in e.get("requires", []):
            fact, _, image = r.partition(":")
            if fact not in facts:
                errs.append(f"{where}: requires unknown fact {fact}")
            elif fact == "fpga_image" and image not in IMAGES:
                errs.append(f"{where}: requires fpga_image:<{'|'.join(IMAGES)}>")
            elif fact != "fpga_image" and image:
                errs.append(f"{where}: only fpga_image takes a value")
        if e.get("status", "active") not in ("active", "retired"):
            errs.append(f"{where}: status must be active or retired")
        if e.get("dated") not in DATED:
            errs.append(f"{where}: dated must be one of {DATED}")
        if "legacy_caps" in e and e.get("rev") != 1:
            errs.append(f"{where}: the status caps list is frozen: a new feature has no legacy_caps")
    if revs and max(revs) != t["revision"]:
        errs.append(f"revision {t['revision']} is not the highest rev ({max(revs)})")
    # Several entries may share a rev (they shipped in one table bump), but no bump is skipped.
    missing = sorted(set(range(1, t["revision"] + 1)) - set(revs))
    if missing:
        errs.append(f"no entry has rev {missing}: every bump of revision adds at least one entry")
    seen = set()
    for r in t["releases"]:
        v = r.get("firmware", "")
        if not VERSION_RE.match(v):
            errs.append(f"release {v!r}: not a version")
        if v in seen:
            errs.append(f"release {v}: twice")
        seen.add(v)
        if not isinstance(r.get("gateware"), int):
            errs.append(f"release {v}: gateware must be an integer")
    return errs


DOCS = os.path.join(REPO, "docs")


def gh_slug(text):
    """GitHub's heading anchor: lower case, punctuation dropped (except - and _), spaces to -."""
    return re.sub(r"[^\w\- ]", "", text.strip().lower()).replace(" ", "-")


def doc_anchors(path):
    """Every anchor a markdown file has: its headings' slugs (a repeated slug gets -1, -2, ...)
    outside fenced code blocks, and its <a id="..."> / <a name="..."> anchors."""
    anchors, seen, fence = set(), {}, False
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.lstrip().startswith("```"):
                fence = not fence
                continue
            if fence:
                continue
            m = re.match(r"^#{1,6}\s+(.*?)\s*#*\s*$", line)
            if m:
                slug = gh_slug(m.group(1))
                n = seen.get(slug, 0)
                seen[slug] = n + 1
                anchors.add(slug if n == 0 else f"{slug}-{n}")
            anchors.update(re.findall(r'<a\s+(?:id|name)="([^"]+)"', line))
    return anchors


def check_docs(t):
    errs, cache = [], {}
    for name, e in t["features"].items():
        link = e.get("docs")
        if not link or re.match(r"^https?://", link):
            continue
        rel, _, anchor = link.partition("#")
        path = os.path.normpath(os.path.join(DOCS, rel))
        if not path.startswith(DOCS + os.sep) or not os.path.isfile(path):
            errs.append(f"feature {name}: docs {link}: no file docs/{rel}")
            continue
        if anchor:
            if path not in cache:
                cache[path] = doc_anchors(path)
            if anchor not in cache[path]:
                errs.append(f"feature {name}: docs {link}: docs/{rel} has no heading or <a id> for #{anchor}")
    return errs


def check_code(t):
    errs = check_docs(t)
    consts = fw_constants()
    for name, e in t["features"].items():
        c = e.get("gw_const")
        if c is None:
            continue
        if c not in consts:
            errs.append(f"feature {name}: gw_const {c} is not #defined in stm32h563/src")
        elif consts[c] != e["gateware"]:
            errs.append(f"feature {name}: gateware {e['gateware']} but {c} is {consts[c]}")
    legacy = {e["legacy_caps"] for e in t["features"].values() if "legacy_caps" in e}
    legacy |= {f["legacy_caps"] for f in t["facts"].values() if "legacy_caps" in f}
    extra = status_caps_names() - legacy
    if extra:
        errs.append("the status caps list is frozen, but cloud_caps.c writes names no entry has as "
                    f"legacy_caps: {sorted(extra)}. Put a new feature in features/features.toml only.")
    return errs


def build_json(t, sha):
    facts = {name: {k: v for k, v in f.items() if k != "note"} for name, f in t["facts"].items()}
    features = {}
    for name, e in t["features"].items():
        out = {"rev": e["rev"], "firmware": e["firmware"]}
        if "gateware" in e:
            out["gateware"] = e["gateware"]
        out["board"] = e.get("board", "any")
        if e.get("requires"):
            out["requires"] = e["requires"]
        for k in ("legacy_caps", "legacy_frame", "docs"):
            if k in e:
                out[k] = e[k]
        if e.get("status", "active") != "active":
            out["status"] = e["status"]
        features[name] = out
    doc = {
        "_generated": BANNER,
        "schema": t["schema"],
        "revision": t["revision"],
        "api": t["api"],
        "min_client_api": t["min_client_api"],
        "table_sha256": sha,
        "floor": t["floor"],
        "docs_base": t["docs_base"],
        "facts": facts,
        "releases": t["releases"],
        "features": features,
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def build_h(t):
    return f"""/* {BANNER} */
#ifndef BP_FEATURES_H
#define BP_FEATURES_H

/* The revision of features/features.toml this firmware is built from. The pod announces it as
   features_rev (status, cloud capabilities frame); clients take every feature with rev <= it from
   their copy of features/features.json instead of a list the pod sends. */
#define BP_FEATURES_REV {t['revision']}u

/* The client API level (features.toml `api`), announced as "api" next to features_rev: it goes up
   only for a change a client built for an older level would misread. */
#define BP_API {t['api']}u

/* The lowest "client_api" a JSON command may carry (absent = 0), announced as "min_client_api".
   Below it the pod refuses with BP0030 client_too_old (cmd_gate_client_api). Raised only on
   purpose, in a release pull request. A test build may set BP_MIN_CLIENT_API_OVERRIDE. */
#ifdef BP_MIN_CLIENT_API_OVERRIDE
#define BP_MIN_CLIENT_API BP_MIN_CLIENT_API_OVERRIDE
#else
#define BP_MIN_CLIENT_API {t['min_client_api']}u
#endif

#endif /* BP_FEATURES_H */
"""


def release(version):
    """The release pull request: "next" -> version, and a [[releases]] row with the gateware the
    release embeds (ice40/release/MANIFEST)."""
    if not VERSION_RE.match(version):
        raise SystemExit(f"gen_features: {version!r} is not a version")
    with open(TABLE, encoding="utf-8") as f:
        text = f.read()
    t = tomllib.loads(text)
    if any(r["firmware"] == version for r in t["releases"]):
        raise SystemExit(f"gen_features: release {version} is already in the table")
    with open(MANIFEST, encoding="utf-8") as f:
        m = re.search(r"^gateware_version=(\d+)$", f.read(), re.M)
    if not m:
        raise SystemExit("gen_features: no gateware_version in ice40/release/MANIFEST")
    text = re.sub(r'^firmware = "next"$', f'firmware = "{version}"', text, flags=re.M)
    row = (f'[[releases]]\nfirmware = "{version}"\ngateware = {m.group(1)}\n'
           f'date = "{datetime.date.today().isoformat()}"\n')
    last = list(re.finditer(r"^\[\[releases\]\]\n(?:[^\n\[][^\n]*\n)*", text, re.M))
    if not last:
        raise SystemExit("gen_features: no [[releases]] in the table")
    end = last[-1].end()
    text = text[:end] + "\n" + row + text[end:]
    with open(TABLE, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"gen_features: release {version} (gateware {m.group(1)}) added")


def main(argv):
    if len(argv) == 3 and argv[1] == "--release":
        release(argv[2])
        argv = argv[:1]
    t, sha = load()
    errs = validate(t)
    if not errs:
        errs = check_code(t)
    if len(argv) == 3 and argv[1] == "--check-release":
        v = argv[2].lstrip("v")
        nxt = sorted(n for n, e in t["features"].items() if e["firmware"] == "next")
        if nxt:
            errs.append(f"release {v}: still \"next\": {nxt} (run tools/gen_features.py --release {v})")
        if not any(r["firmware"] == v for r in t["releases"]):
            errs.append(f"release {v}: no [[releases]] row (run tools/gen_features.py --release {v})")
    if errs:
        for e in errs:
            print(f"gen_features: {e}", file=sys.stderr)
        return 1
    outputs = {OUT_JSON: build_json(t, sha), OUT_H: build_h(t)}
    check = len(argv) >= 2 and argv[1] in ("--check", "--check-release")
    stale = []
    for path, text in outputs.items():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            if check:
                stale.append(os.path.relpath(path, REPO))
            else:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text)
    if stale:
        print(f"gen_features: stale {', '.join(stale)}: run python3 tools/gen_features.py",
              file=sys.stderr)
        return 1
    print(f"gen_features: {len(t['features'])} features, {len(t['facts'])} facts, "
          f"revision {t['revision']}, api {t['api']} (min client {t['min_client_api']})" + (" (up to date)" if check else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
